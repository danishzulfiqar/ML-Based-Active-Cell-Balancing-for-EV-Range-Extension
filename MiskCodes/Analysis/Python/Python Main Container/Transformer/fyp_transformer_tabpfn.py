from skopt import gp_minimize
from skopt.space import Real
from skopt.callbacks import DeltaYStopper
from skopt.utils import use_named_args
from functools import partial

# -------------------------------
# Define the EarlyStopper callback class
# -------------------------------
class EarlyStopper:
    def __init__(self, delta=0.01, patience=40):
        """
        delta: Minimum improvement required (in objective value) to reset the counter.
        patience: Number of iterations with no sufficient improvement before stopping.
        """
        self.delta = delta
        self.patience = patience
        self.best = None
        self.counter = 0

    def __call__(self, res):
        current_best = min(res.func_vals)  # Note: lower is better (we're minimizing negative prediction)
        if self.best is None or current_best < self.best - self.delta:
            self.best = current_best
            self.counter = 0
        else:
            self.counter += 1

        print(f"EarlyStopper: counter = {self.counter}, best objective = {-self.best:.2f}")
        if self.counter >= self.patience:
            print("Early stopping triggered.")
            return True  # Returning True stops the optimization
        return False

# -------------------------------
# Define the objective function for minimization
# -------------------------------
def objective_function(params, x5):
    x1, x2, x3, x4 = params
    # Round values for consistency
    x1 = round(x1, 2)
    x2 = round(x2, 2)
    x3 = round(x3, 2)
    x4 = round(x4, 8)

    # Here, predict_range is assumed to be your prediction function which takes inputs:
    # w1, w2, w3, wPL, and DC (here, x5 is used as the encoded DC value).
    # We return the negative of the predicted range since we wish to maximize it.
    return -predict_range(x1, x2, x3, x4, x5)

# -------------------------------
# Define a simple progress callback (optional)
# -------------------------------
def print_progress(res):
    iteration = len(res.func_vals)
    current_best = -min(res.func_vals)
    current_params = res.x_iters[-1]
    print(f"Iteration {iteration}: Current best predicted range = {current_best:.2f}, Latest params = {current_params}")

# -------------------------------
# Bayesian Optimization Loop
# -------------------------------
# Define the search space for x1, x2, x3, and x4
space = [
    Real(0.0, 1.0, name='x1'),
    Real(0.0, 1.0, name='x2'),
    Real(0.0, 1.0, name='x3'),
    Real(0.0, 0.0001, name='x4')
]

# Initialize a dictionary to store the optimal results for each x5
optimal_results = {}

# Loop over each fixed x5 value from 0 to 6
for x5_value in range(7):
    print(f"\nOptimizing for x5 = {x5_value}...")

    # Create a version of the objective function with x5 fixed
    fixed_obj = partial(objective_function, x5=x5_value)

    # Create a new EarlyStopper instance for each optimization run
    early_stopper = EarlyStopper(delta=0.01, patience=40)

    # Run Bayesian Optimization with callbacks
    result = gp_minimize(
        fixed_obj,
        space,
        n_calls=300,
        n_initial_points=20,
        acq_func='EI',
        random_state=42,
        callback=[print_progress, early_stopper]
    )

    best_x1, best_x2, best_x3, best_x4 = result.x
    optimal_range = -result.fun  # Reverse the negative sign

    optimal_results[x5_value] = {
        "x1": round(best_x1, 2),
        "x2": round(best_x2, 2),
        "x3": round(best_x3, 2),
        "x4": round(best_x4, 6),
        "optimal_range": round(optimal_range, 2)
    }

# -------------------------------
# Print the optimal results for each x5 value
# -------------------------------
for x5_value, results in optimal_results.items():
    print(f"\nFor x5 = {x5_value}:")
    print(f"  Optimal inputs: x1 = {results['x1']:.2f}, x2 = {results['x2']:.2f}, x3 = {results['x3']:.2f}, x4 = {results['x4']:.6f}")
    print(f"  Maximum predicted range: {results['optimal_range']:.2f}")

